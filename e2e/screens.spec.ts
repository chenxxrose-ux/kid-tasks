import { test, expect } from '@playwright/test'

// 版面檢查用：SHOTS=1 才會跑，把每一頁存成 iPhone 截圖
test.skip(!process.env.SHOTS, '只在檢查版面時跑')
const OUT = process.env.SHOTS ?? ''

test('每一頁的截圖', async ({ browser }) => {
  const kidCtx = await browser.newContext()
  const momCtx = await browser.newContext()
  const login = async (ctx: typeof kidCtx, email: string) => {
    const p = await ctx.newPage()
    await p.goto('/')
    await p.screenshot({ path: `${OUT}/0-login.png` })
    await p.getByLabel('Email').fill(email)
    await p.getByLabel('密碼').fill('test-password')
    await p.getByRole('button', { name: '登入' }).click()
    return p
  }
  const kid = await login(kidCtx, 'kid@test.local')
  const mom = await login(momCtx, 'mom@test.local')
  await expect(mom.locator('.visit')).toBeVisible()
  await mom.getByRole('button', { name: '交代一件事' }).click()
  await mom.getByLabel('要交代的事').fill('把客廳的報紙拿去回收')
  await mom.getByRole('button', { name: '交代', exact: true }).click()
  const add = async (title: string, when: string) => {
    const box = kid.locator('.teach')
    await box.getByRole('button', { name: '記下老師說的事' }).click()
    await box.getByLabel('老師交代什麼').fill(title)
    await box.getByRole('button', { name: when }).click()
    await box.getByRole('button', { name: '記下來' }).click()
  }
  await add('數學習作第 3 頁訂正完交給小老師', '明天')
  await add('聯絡簿請家長簽名', '老師沒說')
  await kid.locator('.teach').getByRole('button', { name: '記下老師說的事' }).click()
  await kid.screenshot({ path: `${OUT}/1b-kid-teacher-form.png`, fullPage: true })
  await kid.locator('.teach').getByRole('button', { name: '取消' }).click()
  await mom.getByRole('button', { name: /^留言/ }).click()
  await mom.getByRole('textbox', { name: '留言' }).fill('段考加油！今天早點睡，明天早上記得帶水壺和體育服')
  await mom.getByRole('button', { name: '送出' }).click()
  await expect(kid.locator('.mban')).toBeVisible()
  await kid.screenshot({ path: `${OUT}/1-kid-today.png`, fullPage: true })
  await mom.getByRole('button', { name: /^今日事/ }).click()
  await mom.screenshot({ path: `${OUT}/2-mom-today.png`, fullPage: true })
  // 長按拖曳中的樣子
  const pm = mom.locator('.group', { hasText: '放學後' }).locator('.sortrow')
  await pm.nth(1).evaluate((el) => el.scrollIntoView({ block: 'center' }))
  const r = (await pm.nth(1).boundingBox())!
  await mom.mouse.move(r.x + r.width / 2, r.y + r.height / 2)
  await mom.mouse.down()
  await mom.waitForTimeout(500)
  await mom.mouse.move(r.x + r.width / 2, r.y + r.height * 2.2, { steps: 8 })
  await mom.screenshot({ path: `${OUT}/2b-mom-drag.png` })
  await mom.mouse.move(r.x + r.width / 2, r.y + r.height / 2, { steps: 8 })
  await mom.mouse.up()
  await kid.getByRole('button', { name: /^留言/ }).click()
  await kid.getByRole('textbox', { name: '留言' }).fill('好')
  await kid.getByRole('button', { name: '送出' }).click()
  await kid.screenshot({ path: `${OUT}/3-kid-msgs.png` })
  await mom.getByRole('button', { name: /^存錢筒/ }).click()
  await mom.getByRole('button', { name: '記一筆存入' }).click()
  await mom.getByLabel('金額').fill('12350')
  await mom.getByLabel('是什麼錢').fill('紙本帳轉入')
  await mom.getByRole('button', { name: '存入', exact: true }).click()
  await kid.getByRole('button', { name: /^存錢筒/ }).click()
  await expect(kid.locator('.big')).toHaveText('NT$ 12,350')
  await kid.getByRole('button', { name: '申請領錢' }).click()
  await kid.getByLabel('金額').fill('350')
  await kid.getByLabel('要用在哪裡').fill('買參考書')
  await kid.getByRole('button', { name: '送出申請' }).click()
  await expect(kid.getByText('等媽媽們確認')).toBeVisible()
  await kid.screenshot({ path: `${OUT}/4-kid-bank.png`, fullPage: true })
  await expect(mom.getByText('樂樂想領 NT$ 350')).toBeVisible()
  await mom.screenshot({ path: `${OUT}/5-mom-bank.png`, fullPage: true })
  await mom.getByRole('button', { name: /^安排/ }).click()
  await mom.screenshot({ path: `${OUT}/6-mom-plan.png`, fullPage: true })
  await kid.getByRole('button', { name: /^今日事/ }).click()
  await kidCtx.setOffline(true)
  await kid.locator('.askbox').getByRole('button').first().click()
  await kid.screenshot({ path: `${OUT}/7-kid-offline.png` })
  await kidCtx.close()
  await momCtx.close()
})
